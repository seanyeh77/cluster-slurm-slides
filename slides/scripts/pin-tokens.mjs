// Write styles/tokens-pinned.css: the light tokens plus the "teaching" preset
// from styles/tokens.css, re-scoped to `body, #app`.
// A host page (for example an artifact viewer) may set data-theme="dark" on
// <html>, which overrides tokens defined at :root. Pinning the values on body
// and #app keeps the deck in the teaching preset whatever the host sets.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'styles')
const css = readFileSync(join(dir, 'tokens.css'), 'utf8')

const block = (selector) => {
  const start = css.indexOf(`${selector} {`)
  if (start < 0) throw new Error(`tokens.css has no ${selector} block`)
  const open = css.indexOf('{', start)
  return css.slice(open + 1, css.indexOf('}', open)).trim()
}

const out = `/* Generated by scripts/pin-tokens.mjs from styles/tokens.css. Do not edit by hand. */
body, #app {
  ${block(':root')}

  /* teaching preset */
  ${block('[data-theme="teaching"]')}
}
`
writeFileSync(join(dir, 'tokens-pinned.css'), out)
console.log('styles/tokens-pinned.css written')
